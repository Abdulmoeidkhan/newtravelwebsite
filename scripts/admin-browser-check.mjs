await page.getByLabel('Email address').fill('admin@example.test');
await page.getByLabel('Password', { exact: true }).fill('Local-test-only-123!');
await page.getByRole('button', { name: 'Sign in securely' }).click();
await page.getByRole('heading', { name: 'Package collection' }).waitFor();
await page.getByRole('button', { name: 'Edit The Golden Journey', exact: true }).waitFor();
await page.screenshot({ path: 'artifacts/admin-desktop.png', fullPage: true });
await page.getByRole('button', { name: 'Add package', exact: true }).click();
await page.getByRole('button', { name: 'Save draft' }).click();
await page.getByRole('alert').waitFor();
await page.getByLabel('Package name', { exact: true }).fill('QA private journey');
await page.getByLabel('Starting price per person').fill('375000');
await page.getByLabel('Departure months').fill('2027-01');
