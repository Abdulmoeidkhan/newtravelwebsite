await publicPage.goto(base);
await publicPage.locator('.package-card').first().waitFor();
await publicPage.getByRole('button', { name: 'View all packages' }).click();
assert.equal(await publicPage.locator('.package-card').count(), 4);
assert.equal(await publicPage.getByRole('heading', { name: 'QA private journey' }).count(), 0);
await page.getByRole('button', { name: 'Edit QA private journey', exact: true }).click();
await page.getByLabel('Publish on the website').check();
await page.getByRole('button', { name: 'Save & publish package' }).click();
await page.getByRole('heading', { name: 'Package collection' }).waitFor();
await publicPage.getByRole('heading', { name: 'QA private journey' }).waitFor();
await page.getByRole('button', { name: 'Reviews & Shorts', exact: true }).click();
await page.getByLabel('Google Business Place ID').waitFor();
await page.getByLabel('Video title').fill('Updated test journey');
await page.getByLabel('YouTube URL or video ID').fill('https://www.youtube.com/shorts/abcdefghijk');
await page.getByRole('button', { name: 'Save media settings' }).click();
await page.getByText('Media settings saved. The website updates automatically.').waitFor();
await publicPage.getByRole('button', { name: 'Play Updated test journey' }).waitFor();
await publicPage.route('https://www.youtube-nocookie.com/**', route => route.fulfill({ body: '<html><body>Test player</body></html>', contentType: 'text/html' }));
await publicPage.getByRole('button', { name: 'Play Updated test journey' }).click();
assert.match(await publicPage.locator('#shorts iframe').getAttribute('src'), /youtube-nocookie.com\/embed\/abcdefghijk/);
await page.getByRole('button', { name: 'Packages', exact: true }).click();
await page.getByRole('button', { name: 'Delete QA private journey', exact: true }).click();
await page.getByRole('button', { name: 'Keep package' }).click();
assert.equal(await page.getByRole('button', { name: 'Edit QA private journey' }).count(), 1);
await page.getByRole('button', { name: 'Delete QA private journey', exact: true }).click();
await page.getByRole('button', { name: 'Delete package', exact: true }).click();
await publicPage.getByRole('heading', { name: 'QA private journey' }).waitFor({ state: 'detached' });
for (const width of [1440, 768, 390, 320]) {
  await page.setViewportSize({ width, height: 900 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Admin overflow at ${width}`);
  if (width === 390) await page.screenshot({ path: 'artifacts/admin-mobile.png', fullPage: true });
}
await page.getByRole('button', { name: 'Sign out' }).click();
await page.getByRole('heading', { name: 'Welcome back.' }).waitFor();
assert.deepEqual(errors, []);
await browser.close();
console.log('Admin browser checks passed: ordinary-user denial, sign-in, draft creation/privacy, validation, live publishing, media editing, video embedding, delete confirmation, mobile layout, and sign-out.');
